"""gen_pass.py CODELAB.md OUT.sh [OLD=>NEW ...]

Writes a bash script that runs every ```bash block of the codelab in order,
as written apart from the OLD=>NEW substitutions. A block whose first line is
"# terminal 2" runs in the background as the reader's second terminal, until
the next such block or the next step, when it gets Ctrl+C (SIGINT)."""
import re
import sys

src, out, subs = sys.argv[1], sys.argv[2], [a.split("=>", 1) for a in sys.argv[3:]]
lines = open(src).read().splitlines()
blocks, step, i = [], "", 0
while i < len(lines):
    if lines[i].startswith("## "):
        step = lines[i][3:].strip()
    m = re.match(r"^(\s*)```(\w*)\s*$", lines[i])
    if m:
        ind, lang, body = len(m.group(1)), m.group(2), []
        i += 1
        while not re.match(r"^\s*```\s*$", lines[i]):
            body.append(lines[i][ind:])
            i += 1
        if lang == "bash":
            text = "\n".join(body)
            for old, new in subs:
                text = text.replace(old, new)
            blocks.append((step, text))
    i += 1

o = ['#!/bin/bash', f'# generated by gen_pass.py from {src}', 'set -o pipefail', 'L=$PASSLOG_DIR; T2=',
     'stop_t2() { [ -n "$T2" ] || return 0; kill -INT -- -$T2 2>/dev/null; sleep 0.5; kill -- -$T2 2>/dev/null;'
     ' echo "--- terminal 2 output:"; cat $T2LOG; T2=; }',
     'now() { date -u +%T.%N | cut -c1-12; }',
     "trap 'echo \"!!! exit status $? at line $LINENO\"' ERR"]
last = None
for n, (st, text) in enumerate(blocks, 1):
    if st != last:
        o += ['stop_t2', f'echo; echo "=== STEP {st} at $(now)"']
        last = st
    first, _, rest = text.partition("\n")
    if first.strip() == "# terminal 2":
        o += ['stop_t2', f'T2LOG=$L/t2_{n}.log', f"cat > $L/t2_{n}.sh <<'T2EOF'", rest, 'T2EOF',
              f'echo "--- block {n} in terminal 2 at $(now):"; cat $L/t2_{n}.sh',
              # setsid -f: the reader's second terminal is not a child of the first, so `wait` there ignores it
              f'setsid -f bash -c "echo \\$\\$ > $L/t2.pid; exec bash $L/t2_{n}.sh" > $T2LOG 2>&1; sleep 1; T2=$(cat $L/t2.pid)']
    else:
        o += [f'echo "--- block {n} at $(now)"; B0=$(date +%s.%N)', 'set -v', text, 'set +v',
              f'echo "--- block {n} done at $(now), $(awk "BEGIN {{printf \\"%.1f\\", $(date +%s.%N) - $B0}}") s"']
o += ['stop_t2', 'echo "=== END at $(now)"']
open(out, "w").write("\n".join(o) + "\n")
print(f"{len(blocks)} bash blocks")
